!> Reference driver for N2b criterion 1 (COARE part): CROCO's default bulk formulae
!! (COARE 3.0 with BULK_GUSTINESS and BULK_LW, ~/pyOCEAN_refs/croco git ab63b58,
!! OCEAN/bulk_flux.F) on the points that validation/bulk_points/points.py writes.
!!
!! bulk_point is generated by build_reference.sh: the scalar block of bulk_flux_tile
!! (bulk_flux.F:199-659) and the functions (:758-974) copied verbatim by sed, with the
!! (i,j) arrays replaced by scalar arguments and one change, documented there: the
!! specific humidity is given (Q = RH with RH = q_air) instead of spec_hum (:207), because
!! pyOCEAN's input is q, and spec_hum's g/kg branch (RH >= 2) cannot hold q < 2 g/kg.
!! Model constants as scalars.h:633,640,643 (g = 9.81, Cp = 3985, vonKar = 0.41) and
!! rho0 = 1025 (croco.in:61).
!!
!! Usage: croco_bulk_driver in.txt out.txt
!!   in.txt : first line n, then n lines "u10 v10 t_air_c q_air sst_c lw_down"
!!            (m/s, degC, kg/kg, degC, W/m2).
!!   out.txt: n lines with points.COARE_OUTPUT_FIELDS, CROCO's own (kinematic) values:
!!            sustr svstr [m2/s2], hfsen hflat hflw [K m/s, positive into the ocean],
!!            evap [m/s], Cd, rhoAir [kg/m3], Wstar, Tstar, Qstar, delW (final, with
!!            gustiness), Qsea, charn, patm [Pa].
program croco_bulk_driver
  implicit none
  real, parameter :: rho0 = 1025.0          ! croco.in:61
  real, parameter :: Cp = 3985.0            ! scalars.h:640
  integer :: n, i, u
  character(len=512) :: fin, fout
  real :: u10, v10, tair, qair, tsea, lwd
  real :: wspd, radlw, srf_scale, rho0i
  real :: hfsen, hflat, hflw, evap, Cd, rhoAir, aer, cer
  real :: Wstar, Tstar, Qstar, delW, Qsea, charn, patm
  real :: sustr, svstr

  call get_command_argument(1, fin) ; call get_command_argument(2, fout)
  srf_scale = 1./(rho0*Cp)                  ! get_bulk.F:384, radlw kinematic
  rho0i = 1.0/rho0                          ! bulk_flux.F:171
  open(newunit=u, file=trim(fin), status='old', action='read')
  read(u, *) n
  open(20, file=trim(fout), status='replace', action='write')
  do i = 1, n
    read(u, *) u10, v10, tair, qair, tsea, lwd
    wspd = SQRT(u10**2.0 + v10**2.0)        ! get_bulk.F:888 (wind given at rho points)
    radlw = srf_scale*lwd                   ! get_bulk.F:384, 958-960
    call bulk_point(wspd, tair, qair, tsea, radlw, rho0, &
                    hfsen, hflat, hflw, evap, Cd, rhoAir, aer, cer, &
                    Wstar, Tstar, Qstar, delW, Qsea, charn, patm)
    ! bulk_flux.F:706-712 and :728-734 with both neighbours equal to this point
    sustr = (0.5*(cer+cer))*(0.5*(aer+aer))*u10*rho0i
    svstr = (0.5*(cer+cer))*(0.5*(aer+aer))*v10*rho0i
    write(20, '(15ES25.17)') sustr, svstr, hfsen, hflat, hflw, evap, Cd, rhoAir, &
                             Wstar, Tstar, Qstar, delW, Qsea, charn, patm
  enddo
  close(u) ; close(20)
end program croco_bulk_driver

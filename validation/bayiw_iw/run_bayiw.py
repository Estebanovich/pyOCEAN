#!/usr/bin/env python
"""
Baroclinic reproduction of the MITgcm BayIW_Rectan experiment (internal waves
generated by a bay seiche; Cruz Isidro M.Sc. thesis) with the stratified
σ-layer model.

Reference runs (MITgcm, /Volumes/ESTEBAN_MIT/MITgcm/verification/BayIW_Rectan):
    560 × 352 telescopic Cartesian grid (5 km core, 13.3 km margins), 50 z-levels
    (Σ delR = 599.9 m; the 1000 m bathymetry is clipped there), bay 164 m deep,
    f0 = 6.97e-5, linear EOS (tAlpha 2e-4, rhoNil 999.8, S uniform 33.6),
    viscAh = diffKhT = 100 m² s⁻¹, viscAr = diffKrT = 1e-5 m² s⁻¹, Δt = 30 s,
    meridional wind pulse (≤ 0.099 N m⁻² at t = 2.5 h, records every 1200 s centred
    at (n + ½)·1200 s; stage 1 = 0–60 h only, stage 2 has no wind), open S/W/E
    (Orlanski + 30-cell sponge, 1200 s inner / 60 s
    at the boundary), closed N; 120 h.

pyOCEAN configuration (same physics, choices marked):
    σ-layers with the fractions of delR, so the layers equal MITgcm's z-levels in
    the 599.9 m ocean and are compressed in the 164 m bay; ρ₀ = rhoNil (MITgcm's
    rhoConst default) for τ/ρ₀ and the EOS, α = rhoNil·tAlpha; the reference
    density profile is the initial MITgcm profile (no PGF error at rest; the
    Laplacian along σ acts on T − T_ref(z)).  Open S/W/E: Flather + Orlanski +
    the same sponge profile, applied to the baroclinic part only (MITgcm relaxes
    the total velocity towards the radiated boundary value).  Tracers: WENO5-Z
    (MITgcm: centred 2nd order + K_h = 100) — both K_h and the scheme can be set.
    S is uniform, so T alone carries the density.

Output (every 900 s, like the MITgcm dumps), CF NetCDF (iw_output.py):
    pyocean_iw_<tag>_stations.nc — stations (η, T, u, v at cell centres, w at
    interfaces) as a CF timeSeriesProfile, float64;
    pyocean_iw_<tag>_fields.nc — the Y–Z section along the bay axis (i = 280) and
    w and T on z = −110 m and −250 m in a box around the bay, float32 + zlib;
    restarts (float64) every --restart-every hours; the series are rewritten then too.

Usage:  python run_bayiw.py bay|nobay [--hours 120] [--dt 300] [--restart FILE]
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from core.dynamics.sigma_baroclinic import ReferenceProfile, SigmaBaroclinic, set_threads  # noqa: E402
from core.grid.horizontal import create_cartesian_grid_stretched  # noqa: E402
from core.grid.sigma_levels import sigma_from_thicknesses  # noqa: E402
from core.restart import read_restart, write_restart  # noqa: E402
from diagnostics.postmortem import BlowupGuard  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))
import iw_output  # noqa: E402

RUN = Path("/Volumes/ESTEBAN_MIT/MITgcm/verification/BayIW_Rectan")
SCENARIOS = {"realistic": RUN / "input/feb_temp_50zlev_560x352.bin"}
FILES = {"bay": "bahia_01_expand", "nobay": "nobahia_01_expand"}
NX, NY, NZ = 560, 352, 50
RHO_NIL, T_ALPHA, T_REF, F0 = 999.8, 2e-4, 16.582, 6.97e-5
WIND_PERIOD = 1200.0
STATIONS = {"Seiche": (280, 345), "Seiche2": (280, 325), "A": (230, 315), "B": (330, 315),
            "C": (280, 265), "Gamma": (280, 215), "Omega": (280, 315)}
AXIS_I = 280
BOX = (slice(230, 352), slice(200, 360))                    # (j, i) around the bay
DEPTHS = (110.0, 250.0)
SSD_OUT = Path("/Volumes/ESTEBAN_MIT/pyOCEAN_runs/bayiw_iw")            # large outputs live on the SSD
OUT = SSD_OUT if SSD_OUT.parent.exists() else Path(__file__).parent / "out"


def read_mit(path: Path, shape: tuple[int, ...]) -> np.ndarray:
    """MITgcm binary input: big-endian float64 (readBinaryPrec = 64)."""
    return np.fromfile(path, ">f8").reshape(shape)


def mitgcm_delr() -> np.ndarray:
    """delR (surface first) from the run's ``data`` namelist."""
    txt = (RUN / "run_expand/data").read_text()
    block = re.search(r"delR\s*=(.*?)delYFile", txt, re.S).group(1)
    return np.array([float(x) for x in re.findall(r"\d+\.\d*|\d+", block)])


def wind_at(t: float, records: np.ndarray) -> np.ndarray:
    """
    MITgcm periodicExternalForcing (get_periodic_interval.F): record n (0-based) is
    centred at (n + ½)·period, linear in between, cyclic over the records — only in
    stage 1 (0–60 h = the 180 records, data.stage1).  Stage 2 (60–120 h, data.stage2)
    has no wind file, so τ = 0 afterwards (a cyclic repeat gave a second pulse at 60 h).
    """
    nrec = records.shape[0]
    if t >= nrec * WIND_PERIOD:
        return np.zeros_like(records[0])
    s = t / WIND_PERIOD - 0.5
    n0 = int(np.floor(s)) % nrec
    w = s - np.floor(s)
    return (1.0 - w) * records[n0] + w * records[(n0 + 1) % nrec]


def setup(case: str, args) -> tuple[SigmaBaroclinic, object, np.ndarray]:
    stem = FILES[case]
    dx = np.fromfile(RUN / f"input/{stem}_dx.bin", ">f8")
    dy = np.fromfile(RUN / f"input/{stem}_dy.bin", ">f8")
    delr = mitgcm_delr()
    depth = np.minimum(-read_mit(RUN / f"input/{stem}_bat.bin", (NY, NX)), delr.sum())
    H = np.where(depth > 0, depth, np.nan)                     # land (0 in the file) = wall
    hg = create_cartesian_grid_stretched(dx, dy, x0=-1400e3, y0=-1621e3, f0=F0)

    T_mit = read_mit(SCENARIOS[args.scenario], (NZ, NY, NX))[:, 0, 0]       # horizontally uniform
    z_mit = -(np.cumsum(delr) - 0.5 * delr)                                   # level centres, surface first
    alpha = RHO_NIL * T_ALPHA
    rho_mit = RHO_NIL - alpha * (T_mit - T_REF)
    ref = ReferenceProfile(z_mit[::-1], rho_mit[::-1])

    m = SigmaBaroclinic(hg, H, dt=args.dt, n_layers=NZ, rho0=RHO_NIL, t_coef=alpha, t_ref=T_REF, z0=None,
                        closure="constant", nu_const=args.nu, ah=args.ah, kh=args.kh, kv=args.kv,
                        tracer_scheme=args.tracer_scheme, rho_ref=ref, dsigma=sigma_from_thicknesses(delr),
                        open_boundaries=("west", "east", "south"), sponge_cells=30, sponge_tau=(1200.0, 60.0),
                        theta=args.theta, solver=args.solver)
    z = m.layer_heights(np.zeros((NY, NX)))
    T0 = np.interp(z, z_mit[::-1], T_mit[::-1])
    st = m.initial_state(np.zeros((NY, NX)), T0)
    wind = np.fromfile(RUN / "input/merid_local_bay_560x352.bin", ">f8").reshape(-1, NY, NX)
    return m, st, wind


def static_metadata(m: SigmaBaroclinic, args) -> dict:
    """Fixed coordinates of the output (stations, section, box) for iw_output."""
    x = m.hg["x_t"].values
    y = m.hg["y_t"].values
    x = x if x.ndim == 1 else x[0]
    y = y if y.ndim == 1 else y[:, 0]
    ij = list(STATIONS.values())
    return {"stations": STATIONS, "x_st": x[[i for i, _ in ij]], "y_st": y[[j for _, j in ij]],
            "h_st": np.array([m.H[j, i] for i, j in ij]), "sigma_w": m.core.sigma_w[:, 0],
            "x_axis": x[AXIS_I], "i_axis": AXIS_I, "y_axis": y, "h_axis": m.H[:, AXIS_I],
            "depths": DEPTHS, "box": ((BOX[0].start, BOX[0].stop), (BOX[1].start, BOX[1].stop)),
            "x_box": x[BOX[1]], "y_box": y[BOX[0]],
            "attrs": {k: (str(v) if isinstance(v, Path) else v) for k, v in vars(args).items()}}


def interface_heights(m: SigmaBaroclinic, eta: np.ndarray) -> np.ndarray:
    D = np.maximum(np.nan_to_num(m.H + eta, nan=m.fs.d_min), m.fs.d_min)
    return -np.nan_to_num(m.H)[None] + D[None] * m.core.sigma_w[:, :, None]


def vertical_velocity(m: SigmaBaroclinic, st0, st1) -> np.ndarray:
    """
    w at the layer interfaces [m s⁻¹] from the σ-relative ω:
        w = ω + ∂z_w/∂t|_σ + u·∇z_w      (Kasahara 1974 [verificar]; ROMS 'wvlcty')
    with centred horizontal derivatives of z_w at cell centres.
    """
    zw0, zw1 = interface_heights(m, st0.eta), interface_heights(m, st1.eta)
    uc = 0.5 * (st1.u[..., :-1] + st1.u[..., 1:])
    vc = 0.5 * (st1.v[:, :-1, :] + st1.v[:, 1:, :])
    uw = np.concatenate([uc[:1], 0.5 * (uc[1:] + uc[:-1]), uc[-1:]])
    vw = np.concatenate([vc[:1], 0.5 * (vc[1:] + vc[:-1]), vc[-1:]])
    xc, yc = m.hg["x_t"].values, m.hg["y_t"].values
    xc = xc if xc.ndim == 1 else xc[0]
    yc = yc if yc.ndim == 1 else yc[:, 0]
    dzdy, dzdx = np.gradient(zw1, yc, xc, axis=(1, 2))
    return st1.omega + (zw1 - zw0) / m.dt + uw * np.nan_to_num(dzdx) + vw * np.nan_to_num(dzdy)


def at_depth(field: np.ndarray, zf: np.ndarray, zstar: float) -> np.ndarray:
    """Linear interpolation of a (K, ny, nx) field given at heights zf (increasing in K) to z = −zstar."""
    target = -zstar
    k = np.clip(np.argmax(zf >= target, axis=0), 1, zf.shape[0] - 1)
    z_lo = np.take_along_axis(zf, (k - 1)[None], 0)[0]
    z_hi = np.take_along_axis(zf, k[None], 0)[0]
    f_lo = np.take_along_axis(field, (k - 1)[None], 0)[0]
    f_hi = np.take_along_axis(field, k[None], 0)[0]
    w = np.clip((target - z_lo) / np.where(z_hi > z_lo, z_hi - z_lo, 1.0), 0.0, 1.0)
    out = f_lo + w * (f_hi - f_lo)
    return np.where(zf[-1] >= target, np.where(zf[0] <= target, out, np.nan), np.nan)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("case", choices=FILES)
    ap.add_argument("--scenario", choices=SCENARIOS, default="realistic")
    ap.add_argument("--hours", type=float, default=120.0)
    ap.add_argument("--dt", type=float, default=300.0)
    ap.add_argument("--theta", type=float, default=0.6)
    ap.add_argument("--ah", type=float, default=100.0)
    ap.add_argument("--kh", type=float, default=100.0)
    ap.add_argument("--nu", type=float, default=1e-5)
    ap.add_argument("--kv", type=float, default=1e-5)
    ap.add_argument("--tracer-scheme", default="weno5")
    ap.add_argument("--out-every", type=float, default=900.0)
    ap.add_argument("--restart", type=Path, default=None)
    ap.add_argument("--restart-every", type=float, default=12.0, help="hours")
    ap.add_argument("--tag", default="")
    ap.add_argument("--out", type=Path, default=OUT, help="output directory (large: restarts are 1.2 GB)")
    ap.add_argument("--threads", type=int, default=1, help="threads of the compiled kernels (≤ 5 P-cores)")
    ap.add_argument("--solver", choices=("direct", "cg"), default="cg",
                    help="free surface: sparse LU every step, or CG preconditioned with a lagged LU")
    args = ap.parse_args()
    set_threads(args.threads)

    tag = f"{args.case}_{args.scenario}{args.tag}"
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    m, st, wind = setup(args.case, args)
    if args.restart is not None:
        st = read_restart(args.restart, m)
    nsteps = int(round(args.hours * 3600 / args.dt)) - int(round(st.time / args.dt))
    every = int(round(args.out_every / args.dt))
    rst_every = int(round(args.restart_every * 3600 / args.dt))
    guard = BlowupGuard(limits={"eta": 5.0, "u": 3.0, "v": 3.0}, dump_path=out / f"blowup_{tag}.npz",
                        depth=m.H, dt=args.dt, dx=5000.0)
    rec = {k: [] for k in ("t", "eta_st", "T_st", "u_st", "v_st", "w_st", "T_axis", "v_axis", "w_axis",
                           "eta_axis", "w_z", "T_z")}
    stem = out / f"pyocean_iw_{tag}"
    legacy = out / f"pyocean_iw_{tag}.npz"
    saved = stem if stem.with_name(stem.name + "_stations.nc").exists() else legacy if legacy.exists() else None
    if args.restart is not None and saved is not None:
        # continue the saved series up to the restart time (a restart from an earlier file truncates them)
        old = iw_output.read_records(saved, t_max=st.time)
        for k in rec:
            rec[k] = list(old[k])
        print(f"{tag}: continuing {len(rec['t'])} saved records from t = {st.time / 3600:.1f} h", flush=True)
    static = static_metadata(m, args)
    tic = time.time()
    for n in range(nsteps):
        tau_y = np.zeros((NY + 1, NX))
        tau_y[:NY] = wind_at(st.time, wind)                    # MITgcm V-point j = south face of cell j
        prev = st
        st = m.step(st, tau_y=tau_y)
        if (n + 1) % every == 0:
            guard.check(step=n + 1, time=st.time, eta=st.eta, u=st.u, v=st.v)
            w = vertical_velocity(m, prev, st)
            zc, zw = m.layer_heights(st.eta), interface_heights(m, st.eta)
            uc = 0.5 * (st.u[..., :-1] + st.u[..., 1:])
            vc = 0.5 * (st.v[:, :-1, :] + st.v[:, 1:, :])
            rec["t"].append(st.time)
            rec["eta_st"].append([st.eta[j, i] for i, j in STATIONS.values()])
            for name, f in (("T_st", st.T), ("u_st", uc), ("v_st", vc), ("w_st", w)):
                rec[name].append(np.stack([f[:, j, i] for i, j in STATIONS.values()], axis=1))
            # copies, not views: a view would keep the whole 3-D field of every record alive
            # (~240 MB per record — the 57 GB leak of the first BayIW run)
            rec["T_axis"].append(st.T[:, :, AXIS_I].copy())
            rec["v_axis"].append(vc[:, :, AXIS_I].copy())
            rec["w_axis"].append(w[:, :, AXIS_I].copy())
            rec["eta_axis"].append(st.eta[:, AXIS_I].copy())
            rec["w_z"].append(np.stack([at_depth(w[(slice(None),) + BOX], zw[(slice(None),) + BOX], d)
                                        for d in DEPTHS]).astype(np.float32))
            rec["T_z"].append(np.stack([at_depth(st.T[(slice(None),) + BOX], zc[(slice(None),) + BOX], d)
                                        for d in DEPTHS]).astype(np.float32))
            if len(rec["t"]) % 4 == 0:
                hrs = st.time / 3600
                el = (time.time() - tic) / 60
                print(f"{tag}: t = {hrs:6.2f} h  η_Seiche = {st.eta[345, 280]:+.5f} m  max|u| = "
                      f"{np.abs(st.u).max():.3f}  max|w| = {np.nanmax(np.abs(w)) * 1e3:.3f} mm/s  ({el:.1f} min)",
                      flush=True)
        if (n + 1) % rst_every == 0 or n == nsteps - 1:
            write_restart(out / f"restart_{tag}.nc", m, st)
            iw_output.write(stem, {k: np.array(v) for k, v in rec.items()}, static)
    print(f"{tag}: done in {(time.time() - tic) / 60:.1f} min")


if __name__ == "__main__":
    main()

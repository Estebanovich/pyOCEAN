#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Build a reference table of HYCOM flxflg=6 / wndflg=4 bulk fluxes by
# compiling the ORIGINAL HYCOM source fragments (extracted verbatim at build
# time from HYCOM-src, never copied by hand):
#
#   mod_momtum.F90 : function cd_coarep          (Cd, Kara et al. 2005 fit)
#   thermf.F90     : flxflg=4/6 parameter block  (Cl polynomial coefficients)
#   thermf.F90     : satvpr / qsatur6            (Lowe 1977 e_s, mixing ratio)
#   thermf.F90     : flxflg=6 block               (rair, tamts, Cl, Cs)
#
# The driver then applies the flux lines of thermf.F90 (evap, snsibl) and
# mod_momtum.F90 (surtx, surty) with absolute wind (amoflg=0).
#
# Output: tests/data/hycom_kara6_reference.csv, used by tests/test_bulk_kara.py
#
# Usage:  validation/hycom_kara/make_reference.sh   (from the repo root)
# Needs:  gfortran, python3 with numpy; HYCOM-src/ (git-ignored) present.
# ---------------------------------------------------------------------------
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
SRC=$ROOT/HYCOM-src
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# --- extract HYCOM fragments ------------------------------------------------
awk '/logical, parameter :: lvtc/,/real, parameter :: cpcore/' "$SRC/thermf.F90" \
    | grep -v cpcore > "$WORK/kara_params.inc"
awk '/^      satvpr\(t\)=/,/qsatur6\(t6,p6,f6\)=/' "$SRC/thermf.F90" > "$WORK/kara_stmt.inc"
awk '/elseif \(flxflg.eq.6\) then/{f=1;next} f{print} /csh  = 0.9554\*clh/{if(f)exit}' "$SRC/thermf.F90" \
    | sed -e 's/temp(i,j,1,n)/sst/g' -e 's/saln(i,j,1,n)/sss/g' > "$WORK/kara_cl.inc"
awk '/real function cd_coarep/,/end function cd_coarep/' "$SRC/mod_momtum.F90" > "$WORK/cd_coarep.f90"

cat > "$WORK/driver.F90" <<'EOF'
program kara6_reference
  implicit none
  real :: wndx, wndy, airt, vpmx, pair, sst, sss
  real :: wind, rair, slat, ssen, tdif, sssf, tamts, va, qva, q
  real :: clh, csh, evap, snsibl, cdw, surtx, surty
  real, parameter :: rgas=287.1, tzero=273.16, csubp=1005.7, evaplh=2.47e6
  include 'kara_params.inc'
  real :: satvpr, qsatur6, t, t6, p6, f6
  real, external :: cd_coarep
  integer :: ios
  include 'kara_stmt.inc'
  do
    read(*,*,iostat=ios) wndx, wndy, airt, vpmx, pair, sst, sss
    if (ios /= 0) exit
    wind = sqrt(wndx**2 + wndy**2)
! --- mod_momtum.F90, wndflg=4 .and. flxflg=6, amoflg=0
    rair  = pair / (rgas * (tzero+airt) * (1.0+0.608*vpmx))
    cdw   = 1.0e-3*cd_coarep(wind,vpmx,airt,pair,sst)
    surtx = rair*cdw*wind*wndx
    surty = rair*cdw*wind*wndy
! --- thermf.F90, flxflg=6
    include 'kara_cl.inc'
    sssf   = 1.0 - (0.001/1.805)*max(sss-0.03,0.0)
    evap   = slat*clh*wind*(qsatur6(sst,pair,sssf)-vpmx)
    snsibl = ssen*csh*wind* tdif
    write(*,'(15(es24.16e3,:,","))') wndx, wndy, airt, vpmx, pair, sst, sss, &
         cdw, clh, csh, rair, evap, snsibl, surtx, surty
  end do
end program kara6_reference
EOF

# HYCOM is built with 8-byte default reals (-r8)
( cd "$WORK" && gfortran -O0 -fdefault-real-8 -ffree-line-length-none \
      -o kara6 driver.F90 cd_coarep.f90 )

# --- input sweep -------------------------------------------------------------
python3 - "$WORK/inputs.txt" <<'EOF'
import sys
import numpy as np
rng = np.random.default_rng(20261010)
rows = []
# Structured sweep across the fit's regimes and clipping limits
for U in [0.3, 1.0, 1.1, 2.5, 4.99, 5.0, 5.01, 8.0, 15.0, 25.0, 34.0, 40.0]:
    for dT in [-10.0, -4.0, -0.75, -0.3, 0.0, 0.4, 0.75, 3.0, 9.0]:
        for rh in [0.5, 0.95]:
            sst = 26.0
            airt = sst + dT
            p = 101300.0
            es = 100.0 * 6.1078 * np.exp(17.27 * airt / (airt + 237.3))
            r = 0.622 * rh * es / (p - rh * es)
            ang = rng.uniform(0, 2 * np.pi)
            rows.append((U * np.cos(ang), U * np.sin(ang), airt, r, p, sst, 36.0))
# Random cases
for _ in range(400):
    U = rng.uniform(0.0, 40.0)
    ang = rng.uniform(0, 2 * np.pi)
    sst = rng.uniform(2.0, 32.0)
    airt = sst + rng.uniform(-10.0, 9.0)
    p = rng.uniform(97000.0, 104000.0)
    rh = rng.uniform(0.3, 1.0)
    es = 100.0 * 6.1078 * np.exp(17.27 * airt / (airt + 237.3))
    r = 0.622 * rh * es / (p - rh * es)
    rows.append((U * np.cos(ang), U * np.sin(ang), airt, r, p, sst, rng.uniform(0.0, 40.0)))
np.savetxt(sys.argv[1], np.array(rows), fmt="%.10e")
EOF

OUT=$ROOT/tests/data/hycom_kara6_reference.csv
{
  echo "# HYCOM flxflg=6/wndflg=4 reference, generated by validation/hycom_kara/make_reference.sh"
  echo "# from HYCOM-src thermf.F90 + mod_momtum.F90 (cd_coarep), gfortran -fdefault-real-8"
  echo "wndx,wndy,airt_C,vapmix,pair_Pa,sst_C,sss,cd,cl,cs,rho_air,latent_up_Wm2,sensible_up_Wm2,taux,tauy"
  "$WORK/kara6" < "$WORK/inputs.txt"
} > "$OUT"
echo "wrote $(($(wc -l < "$OUT") - 3)) cases to $OUT"
